'use strict';
// gates/audit/geometry-per-gate.js - WHICH GEOMETRIES EACH GATE RUNS, AND THE REASON IT GIVES. #550 item (60),
// jobs/harness-names-three-of-seven-geometries-2026-09-27: theFix asks "say per gate which geometries it uses and why".
//
// Read, not hand-written, so it cannot drift from the gates: for every gates/regress/*.js it collects
//   - the named geometries the file mentions as quoted strings that are keys of gates/lib.js GEOS (comments stripped,
//     so a geometry named only in prose does not count), with L.TA7 expanded to THE DRILL SEVEN's seven names;
//   - literal geometries {w:N,h:N} written in code (a landscape column, a custom height);
//   - the gate's own stated reason: the first comment line in its header that talks about geometry (geometr, GEOS,
//     THE DRILL SEVEN, THE LESSON THREE, R19, 375x761, 320x568), or "not stated in its header".
// KNOW ITS LIMIT: a geometry chosen at run time from an environment variable (CT_GEO52, CT_INV_GEOS, ...) is listed by
// the names the file quotes, which is the default sweep and its narrowing choices together. Usage:
//   node gates/audit/geometry-per-gate.js > claude/agents/geometry-per-gate.md
const fs=require('fs'),path=require('path');
const L=require('../lib');
const NAMES=Object.keys(L.GEOS),DIR=path.join(__dirname,'..','regress');
const lab=(n)=>n+' ('+L.GEOS[n].w+'x'+L.GEOS[n].h+')';
const out=['# Geometries per gate','',
  'Generated by `node gates/audit/geometry-per-gate.js` (#550 item (60)). Do not edit by hand: re-run it. Names are gates/lib.js GEOS keys; THE DRILL SEVEN is L.TA7.','',
  '| gate | named geometries | literal geometries | the reason its header gives |','|---|---|---|---|'];
let n=0,stated=0;
for(const f of fs.readdirSync(DIR).filter(x=>/\.js$/.test(x)).sort()){
  const s=fs.readFileSync(path.join(DIR,f),'utf8');
  const code=s.replace(/\/\*[\s\S]*?\*\//g,'').replace(/\/\/[^\n]*/g,'');
  const used=new Set();
  for(const m of code.matchAll(/['"]([A-Za-z0-9]+)['"]/g))if(NAMES.includes(m[1]))used.add(m[1]);
  if(/\bL\.TA7\b/.test(code))for(const g of L.TA7)used.add(g);
  const lit=[...new Set([...code.matchAll(/\{\s*w\s*:\s*(\d+)\s*,\s*h\s*:\s*(\d+)/g)].map(m=>m[1]+'x'+m[2]))];
  if(!used.size&&!lit.length)continue;n++;
  const hdr=s.split('\n').slice(0,120).filter(l=>/^\s*\/\//.test(l)&&!/CONTROL-RECORD/.test(l));
  const why=hdr.find(l=>/geometr|GEOS|THE DRILL SEVEN|THE LESSON THREE|\bR19\b|375x761|320x568/i.test(l));
  if(why)stated++;
  const cell=(t)=>t.replace(/\|/g,'\\|');
  out.push('| '+f+' | '+([...used].sort().map(lab).join(', ')||'-')+(/\bL\.TA7\b/.test(code)?' (L.TA7)':'')+' | '+(lit.join(', ')||'-')+' | '+
    (why?cell(why.replace(/^\s*\/\/\s*/,'').slice(0,220)):'not stated in its header')+' |');
}
out.push('','Gates with a geometry: '+n+'. Of them, '+stated+' state a reason in their header and '+(n-stated)+' do not.');
console.log(out.join('\n'));
